create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text unique not null,
  nome text not null default '',
  cognome text not null default '',
  img_profilo text,
  ruolo text not null default 'studente' check (ruolo in ('studente', 'docente')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pcto (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  start_date date not null,
  end_date date not null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.iscrizioni (
  id bigint generated by default as identity primary key,
  studente_id uuid not null references public.profiles(id) on delete cascade,
  pcto_id bigint not null references public.pcto(id) on delete cascade,
  data_iscrizione timestamptz not null default now(),
  unique (studente_id, pcto_id)
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_touch_updated_at on public.profiles;
create trigger profiles_touch_updated_at
before update on public.profiles
for each row
execute function public.touch_updated_at();

alter table public.profiles enable row level security;
alter table public.pcto enable row level security;
alter table public.iscrizioni enable row level security;

drop policy if exists "profiles are readable by authenticated users" on public.profiles;
create policy "profiles are readable by authenticated users"
on public.profiles for select
to authenticated
using (true);

drop policy if exists "users can insert own profile" on public.profiles;
create policy "users can insert own profile"
on public.profiles for insert
to authenticated
with check (auth.uid() = id and ruolo = 'studente');

drop policy if exists "users can update own public profile fields" on public.profiles;
create policy "users can update own public profile fields"
on public.profiles for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id and ruolo = (select ruolo from public.profiles where id = auth.uid()));

revoke update on public.profiles from authenticated;
grant update (email, nome, cognome, img_profilo) on public.profiles to authenticated;

drop policy if exists "pcto are visible to everyone" on public.pcto;
create policy "pcto are visible to everyone"
on public.pcto for select
to anon, authenticated
using (true);

drop policy if exists "docenti can create pcto" on public.pcto;
create policy "docenti can create pcto"
on public.pcto for insert
to authenticated
with check (
  exists (
    select 1 from public.profiles
    where profiles.id = auth.uid()
    and profiles.ruolo = 'docente'
  )
);

drop policy if exists "docenti can delete pcto" on public.pcto;
create policy "docenti can delete pcto"
on public.pcto for delete
to authenticated
using (
  exists (
    select 1 from public.profiles
    where profiles.id = auth.uid()
    and profiles.ruolo = 'docente'
  )
);

drop policy if exists "iscrizioni are visible to authenticated users" on public.iscrizioni;
create policy "iscrizioni are visible to authenticated users"
on public.iscrizioni for select
to authenticated
using (true);

drop policy if exists "students can subscribe themselves" on public.iscrizioni;
create policy "students can subscribe themselves"
on public.iscrizioni for insert
to authenticated
with check (
  studente_id = auth.uid()
  and exists (
    select 1 from public.profiles
    where profiles.id = auth.uid()
    and profiles.ruolo = 'studente'
  )
);

drop policy if exists "students can unsubscribe themselves" on public.iscrizioni;
create policy "students can unsubscribe themselves"
on public.iscrizioni for delete
to authenticated
using (studente_id = auth.uid());

